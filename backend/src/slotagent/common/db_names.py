def table(name: str) -> str:
    return f"sa_{name}"


def col(tbl: str, short: str) -> str:
    """짧은 칸 이름 → DB 칸 이름. 'id' 는 그 테이블의 PK."""
    if short == "id":
        return PK[tbl]
    return COLUMNS[tbl][short]


def plain(tbl: str, row: Mapping[str, Any]) -> dict:
    """DB 행(dict) → 짧은 이름 dict (예시 JSON·계약과 같은 모양). PK 는 'id'."""
    back = {v: k for k, v in COLUMNS[tbl].items()}
    out = {back.get(k, k): v for k, v in row.items()}
    pk = col(tbl, "id")
    if pk in row:
        out["id"] = row[pk]
    return out
