import { test, expect } from "@playwright/test";

test("comparison completes, keeps a snapshot and restores it after reload", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "에이전트의 도구를 바꾸면 더 나아질까요?" })).toBeVisible();
  await page.screenshot({ path: `test-results/home-${test.info().project.name}.png`, fullPage: true });
  await page.getByRole("navigation", { name: "주 메뉴" }).getByRole("button", { name: "새 비교", exact: true }).click();
  await page.getByRole("button", { name: "이 에이전트로 계속하기" }).click();
  const custom = page.getByRole("checkbox", { name: "직접 만든 도구 비교에 포함" });
  await custom.uncheck();
  await page.getByRole("checkbox", { name: "필요한 것만 비교에 포함" }).uncheck();
  await expect(page.getByRole("button", { name: "이 후보들로 시험 정하기" })).toBeDisabled();
  await page.getByRole("checkbox", { name: "필요한 것만 비교에 포함" }).check();
  await page.getByRole("button", { name: "이 후보들로 시험 정하기" }).click();
  await expect(page.getByText("184회", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "안전하게 시험 시작하기" }).click();
  await page.getByRole("button", { name: "이 설정으로 예시 시험 시작" }).click();
  await page.getByRole("button", { name: "시험 중단", exact: true }).click();
  await expect(page.getByRole("heading", { name: "무엇이 더 나아지면 좋을까요?" })).toBeVisible();
  await page.getByRole("button", { name: "안전하게 시험 시작하기" }).click();
  await page.getByRole("button", { name: "이 설정으로 예시 시험 시작" }).click();
  await page.getByRole("button", { name: "완료 예시 보기" }).click();
  await expect(page.getByRole("heading", { name: "필요한 도구만 남기면, 더 가볍게 일할 수 있어요" })).toBeVisible();
  await page.screenshot({ path: `test-results/results-${test.info().project.name}.png`, fullPage: true });
  await page.getByRole("button", { name: "한 장 요약 만들기" }).click();
  await page.getByRole("button", { name: "공유 링크 만들기" }).click();
  await expect(page.getByRole("dialog")).toContainText("다른 사람이 열 수 있는 공유 링크는 생성하지 않아요");
  await page.keyboard.press("Escape");
  await page.getByRole("navigation", { name: "주 메뉴" }).getByRole("button", { name: "비교 기록", exact: true }).click();
  await expect(page.getByRole("row")).toHaveCount(2);
  await page.reload();
  await page.getByRole("navigation", { name: "주 메뉴" }).getByRole("button", { name: "비교 기록", exact: true }).click();
  await page.getByRole("button", { name: "결과 다시 보기" }).click();
  await expect(page.getByText("하루 300회 사용 가정", { exact: false })).toBeVisible();
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
});

test("file registration rejects invalid data and enables supported tool comparisons", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "첫 비교 시작하기" }).click();
  await page.getByRole("button", { name: "파일 업로드로 연결" }).click();
  await page.getByLabel("설정 파일 (JSON)").setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from('{"tools":"bad"}') });
  await expect(page.getByRole("main").getByRole("alert")).toContainText("tools에는");
  await page.getByLabel("설정 파일 (JSON)").setInputFiles({ name: "agent.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify({ name: "테스트 에이전트", job: "이슈를 찾아요", prompt: "도구로 확인한 사실만 답해 주세요.", model: "test-model", tools: [{ s: "github", how: "mcp", access: "read" }] })) });
  await expect(page.getByLabel("에이전트 이름")).toHaveValue("테스트 에이전트");
  await page.getByRole("button", { name: "다음", exact: true }).click();
  await expect(page.getByText("설정 파일의 연결 구성", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "다음", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("확인란에 체크");
  await page.getByRole("checkbox", { name: "도구의 읽기·쓰기 구분과 시험 방식을 확인했어요." }).check();
  await page.getByRole("button", { name: "다음", exact: true }).click();
  await page.getByRole("button", { name: "등록 정보 저장", exact: true }).click();
  await page.getByRole("button", { name: "이 에이전트로 계속하기" }).click();
  await expect(page.getByRole("button", { name: "이 후보들로 시험 정하기" })).toBeEnabled();
});

